package com.ruleup.observability.domain.port

import com.ruleup.observability.domain.event.ObsEvent

/**
 * 이벤트 출구. 도메인이 아는 출구는 **하나뿐**이다.
 *
 * 여러 백엔드로 나눠 보내는 것, 채널로 라우팅하는 것, 백엔드 하나가 실패해도 나머지를 살리는 것 —
 * 전부 **배선의 관심사이지 도메인의 관심사가 아니다.** data 모듈의 합성 구현이 자식들을 들고
 * 그 일을 하고, 도메인은 "정책이 수용한 이벤트를 내보낸다"까지만 안다.
 *
 * 실패 처리도 마찬가지다. [emit] 이 논블로킹이므로 **진짜 실패(업로드·쿼터·재시도)는 비동기로
 * 일어나고 호출자에게 도달하지 않는다.** 그걸 볼 수 있는 건 구현체뿐이므로, 관측·집계·폴백
 * 기록은 전부 구현체 책임이다. 도메인은 방어 코드를 두지 않는다.
 *
 * 계약:
 * - **[emit] 은 절대 예외를 던지지 않는다.** 도메인이 감싸지 않으므로 이 계약이 곧
 *   *"로깅은 앱을 죽이지 않는다"* 를 지탱한다. 자식 실패 격리·프로파일별 재던지기·실패 집계는
 *   구현체 내부에서 한다.
 * - [emit] 은 블로킹하지 않는다. 네트워크·디스크는 내부에서 비동기 처리.
 * - [emit] 은 임의 스레드에서 호출될 수 있다.
 */
interface Sink {
    fun emit(event: ObsEvent)

    /**
     * 버퍼에 쌓인 이벤트를 즉시 내보낸다. 버퍼가 없는 구현은 기본 no-op 그대로 둔다.
     *
     * 프로세스 종료 직전(`onTrimMemory`·크래시 핸들러·백그라운드 전환)에 호출된다.
     * **크래시 직전 이벤트가 관측 데이터 중 가장 값지므로**, 비동기 버퍼를 두는 구현은
     * 반드시 재정의한다.
     *
     * 계약:
     * - [emit] 과 달리 **블로킹이 허용된다.** 호출부가 종료 직전이라는 것을 알고 부른다.
     *   다만 ANR 을 유발하지 않도록 자체 타임아웃을 둔다.
     * - 예외를 던지지 않는다.
     */
    fun flush() {}
}
