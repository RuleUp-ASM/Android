package com.ruleup.observability.domain.port

/**
 * 이벤트 타임스탬프 발급기. 두 시계를 **모두** 찍는 이유는 용도가 다르기 때문이다.
 *
 * 계약:
 * - 이벤트마다 두 함수가 각각 한 번씩 호출된다. 저렴해야 한다.
 * - 스레드 안전해야 하며 예외를 던지지 않는다.
 */
interface Clock {
    /**
     * 벽시계(Unix epoch, ms). **표시·집계용이며 순서 판단에 쓰면 안 된다.**
     * NTP 동기화나 사용자의 시간 변경으로 뒤로 점프할 수 있다.
     */
    fun epochMillis(): Long

    /**
     * 단조 증가 시계(ns). 이벤트 순서와 경과 시간 계산에 쓴다.
     * 절대 시각으로서의 의미는 없고, 기준점은 프로세스 재시작 시 리셋된다.
     * 따라서 **프로세스 간 비교는 불가**하다(오프라인 버퍼를 넘나드는 정렬에는 쓸 수 없다).
     */
    fun monotonicNanos(): Long
}
