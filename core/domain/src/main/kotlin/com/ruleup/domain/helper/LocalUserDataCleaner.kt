package com.ruleup.domain.helper

/**
 * 계정에 귀속된 **단말 저장 데이터**를 지우는 포트.
 *
 * 토큰만 지우는 것으로는 로그아웃이 끝나지 않는다 — 자동인증이 수집해 둔 지오펜스 목표와 통과 기록,
 * 위치 표본, 앱 사용 이벤트와 커서, 진행률 캐시가 그대로 남고, **OS 에 등록된 지오펜스는 계정이
 * 바뀐 뒤에도 계속 울린다**(AUTH-10). 다음 사용자가 앞 사용자의 신호를 자기 것으로 올리게 된다.
 *
 * 계약은 여기 두고 구현은 `:app` 이 꽂는다 — 지울 대상이 여러 feature 에 흩어져 있어, 모으는 일은
 * 전 모듈을 아는 호스트만 할 수 있다.
 */
fun interface LocalUserDataCleaner {
    /**
     * 전부 지운다.
     *
     * **실패해도 로그아웃을 되돌리지 않는다** — 세션은 이미 끝났고, 여기서 예외를 올리면
     * 사용자가 로그아웃하지 못한 채 갇힌다. 구현이 스스로 삼킨다.
     */
    suspend fun clear()
}
